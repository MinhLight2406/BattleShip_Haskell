import { test } from 'node:test'
import assert from 'node:assert/strict'
import { game, peer, within, fleet1, fleet2 } from './helpers.mjs'
import { RECONNECT_GRACE_MS } from '../bridge.mjs'

test('default disconnect reserves P1 for exactly five minutes; wrong token cannot consume or replace it', async (t) => {
  const server = await game(t)
  const first = await peer(server.port); await first.wait('WELCOME 1 P1')
  const { token } = await first.meta('SESSION')
  first.send(fleet1); await first.wait('OK PLACE')
  const second = await peer(server.port); await second.wait('WELCOME 1 P2')
  first.ws.close(); await within(first.closed)
  const state = await second.meta('CONNECTION')
  assert.equal(state.missing[0].player, 'P1')
  assert.ok(Math.abs(state.missing[0].deadline - Date.now() - RECONNECT_GRACE_MS) < 1000)
  assert.equal(server.child.exitCode, null)
  const stranger = await peer(server.port, '127.0.0.1', 'a'.repeat(64))
  assert.equal((await stranger.meta('RESUME_ERROR')).code, 'INVALID_SESSION')
  await within(stranger.closed)
  const third = await peer(server.port); await third.wait('ERROR SERVER_FULL'); await within(third.closed)
  const restored = await peer(server.port, 'localhost', token)
  const session = await restored.meta('SESSION')
  assert.equal(session.token, token)
  assert.equal(session.fleet, fleet1)
  assert.ok(session.frames.includes('WELCOME 1 P1'))
  assert.ok(session.frames.includes('OK PLACE'))
  assert.deepEqual((await restored.meta('CONNECTION')).missing, [])
  const duplicate = await peer(server.port, '127.0.0.1', token)
  assert.equal((await duplicate.meta('RESUME_ERROR')).code, 'SESSION_ACTIVE')
  await within(duplicate.closed)
  restored.send('QUIT')
  await second.wait('GAME_OVER P2 OPPONENT_LEFT')
  assert.deepEqual(await within(server.exited), [0, null])
})

test('resume replays private history without resubmitting a shot; peer cannot fire during pause', async (t) => {
  const server = await game(t)
  const first = await peer(server.port); await first.wait('WELCOME 1 P1')
  const { token } = await first.meta('SESSION')
  const second = await peer(server.port); await second.wait('WELCOME 1 P2')
  first.send(fleet1); await first.wait('OK PLACE')
  second.send(fleet2); await first.wait('TURN P1')
  first.send('FIRE A6'); await first.wait('SHOT A6 HIT'); await first.wait('TURN P1')
  second.ws.close(); await within(second.closed)
  const pause = await first.meta('CONNECTION')
  first.send('FIRE B6')
  assert.deepEqual((await first.meta('CONNECTION')).missing, pause.missing)
  assert.equal(first.frames.includes('SHOT B6 HIT'), false)
  const token2 = JSON.parse(second.frames.find((line) => line.startsWith('{') && JSON.parse(line).type === 'SESSION')).token
  const secondRestored = await peer(server.port, 'localhost', token2)
  const privateReplay = await secondRestored.meta('SESSION')
  assert.equal(privateReplay.fleet, fleet2)
  assert.ok(privateReplay.frames.includes('INCOMING A6 HIT'))
  assert.equal(JSON.stringify(privateReplay).includes('CV=A1'), false)
  await secondRestored.meta('CONNECTION')
  first.ws.close(); await within(first.closed)
  await secondRestored.meta('CONNECTION')
  const restored = await peer(server.port, 'localhost', token)
  const replay = await restored.meta('SESSION')
  assert.equal(replay.frames.filter((line) => line === 'SHOT A6 HIT').length, 1)
  assert.equal(JSON.stringify(replay).includes('CV=A6'), false)
  restored.send('FIRE A6'); await restored.wait('ERROR ALREADY_FIRED A6')
  restored.send('FIRE B6'); await restored.wait('SHOT B6 HIT')
  restored.send('QUIT'); await secondRestored.wait('GAME_OVER P2 OPPONENT_LEFT')
  assert.deepEqual(await within(server.exited), [0, null])
})

for (const inBattle of [false, true]) test(`expiry ${inBattle ? 'mid-game' : 'while placing'} forfeits and late resume gets final Haskell result`, async (t) => {
  const server = await game(t, { reconnectGraceMs: 100 })
  const first = await peer(server.port); await first.wait('WELCOME 1 P1')
  const { token } = await first.meta('SESSION')
  const second = await peer(server.port); await second.wait('WELCOME 1 P2')
  first.send(fleet1); await first.wait('OK PLACE')
  if (inBattle) { second.send(fleet2); await first.wait('TURN P1') }
  first.ws.close(); await within(first.closed)
  await second.wait('GAME_OVER P2 OPPONENT_LEFT')
  assert.deepEqual(await within(server.exited), [0, null])
  const late = await peer(server.port, 'localhost', token)
  const replay = await late.meta('SESSION')
  assert.ok(replay.frames.includes('GAME_OVER P2 OPPONENT_LEFT'))
  await within(late.closed)
})

test('a successful resume cancels its old expiry; a later disconnect starts a new deadline', async (t) => {
  const server = await game(t, { reconnectGraceMs: 500 })
  const first = await peer(server.port); await first.wait('WELCOME 1 P1')
  const { token } = await first.meta('SESSION')
  const second = await peer(server.port); await second.wait('WELCOME 1 P2')
  first.ws.close(); await within(first.closed); await second.meta('CONNECTION')
  const restored = await peer(server.port, 'localhost', token)
  await restored.meta('SESSION'); await restored.meta('CONNECTION')
  await new Promise((resolve) => setTimeout(resolve, 600))
  assert.equal(server.child.exitCode, null, 'cancelled timer must not forfeit restored player')
  restored.ws.close(); await within(restored.closed)
  const pause = await second.meta('CONNECTION')
  // The first empty message acknowledges the preceding resume.
  const missing = pause.missing.length ? pause : await second.meta('CONNECTION')
  assert.ok(missing.missing[0].deadline > Date.now())
  await second.wait('GAME_OVER P2 OPPONENT_LEFT')
  assert.deepEqual(await within(server.exited), [0, null])
})

test('the production five-minute timer forfeits at 300000 ms, never at 299999 ms', async (t) => {
  const server = await game(t)
  const first = await peer(server.port); await first.wait('WELCOME 1 P1')
  const second = await peer(server.port); await second.wait('WELCOME 1 P2')
  // Only the JS clock is accelerated; the socket and Haskell winner are real.
  t.mock.timers.enable({ apis: ['Date', 'setTimeout'] })
  first.ws.close(); await within(first.closed)
  await second.meta('CONNECTION')
  t.mock.timers.tick(299999)
  assert.equal(server.child.exitCode, null)
  assert.equal(second.frames.some((line) => line.startsWith('GAME_OVER ')), false)
  t.mock.timers.tick(1)
  await second.wait('GAME_OVER P2 OPPONENT_LEFT')
  assert.deepEqual(await within(server.exited), [0, null])
  t.mock.timers.reset()
})

test('a rejected replacement fleet cannot corrupt the own fleet saved for resume', async (t) => {
  const server = await game(t)
  const first = await peer(server.port); await first.wait('WELCOME 1 P1')
  const { token } = await first.meta('SESSION')
  first.send(fleet1); await first.wait('OK PLACE')
  first.send(fleet2); await first.wait('ERROR FLEET_ALREADY_PLACED')
  first.ws.close(); await within(first.closed)
  const restored = await peer(server.port, 'localhost', token)
  assert.equal((await restored.meta('SESSION')).fleet, fleet1)
  restored.send('QUIT')
  assert.deepEqual(await within(server.exited), [0, null])
})

test('heartbeat detects a silent network loss, pauses the peer and starts the grace timer', async (t) => {
  const server = await game(t, { heartbeatMs: 100, reconnectGraceMs: 200 })
  const first = await peer(server.port, '127.0.0.1', '', { autoPong: false })
  await first.wait('WELCOME 1 P1')
  const second = await peer(server.port); await second.wait('WELCOME 1 P2')
  // No close/QUIT is sent: the peer simply stops answering websocket pings.
  await within(first.closed)
  assert.equal((await second.meta('CONNECTION')).missing[0].player, 'P1')
  assert.equal(server.child.exitCode, null)
  await second.wait('GAME_OVER P2 OPPONENT_LEFT')
  assert.deepEqual(await within(server.exited), [0, null])
})
